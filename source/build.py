#!/usr/bin/env python3
"""Build Hale into one self-contained HTML file.
   src/shell.html  page skeleton with <!--...--> slots
   src/base.css    shared design system (from Lymphatica), src/hale.css additions
   src/views/*.html one file per section, in order; src/heroart.svg is generated by tools/heroart.py
   src/refs.js     evidence library, generated by cite.py
   src/js/*.js     modules, concatenated in a fixed order inside one closure
Usage: python3 build.py [out.html]"""
import json, re, sys, os, base64, urllib.parse
HERE = os.path.dirname(os.path.abspath(__file__))
SRC = os.path.join(HERE, "src")
FONTS = os.environ.get("HALE_FONTS") or (os.path.join(HERE, "fonts") if os.path.isdir(os.path.join(HERE, "fonts")) else "/home/claude/build/thennow/src/fonts")
OUT = sys.argv[1] if len(sys.argv) > 1 else os.path.join(HERE, "Hale v1.html")
rd = lambda p: open(os.path.join(SRC, p), encoding="utf-8").read()

def fonts_css():
    meta = json.load(open(os.path.join(FONTS, "fonts.json")))
    out = ["/* Embedded open-licence fonts (SIL Open Font License 1.1): Newsreader, Atkinson Hyperlegible and IBM Plex Mono, so the guide looks the same offline and makes no third-party requests. */"]
    for f in meta:
        b64 = open(os.path.join(FONTS, f["file"] + ".b64")).read().strip()
        out.append('@font-face{font-family:"%s";font-style:%s;font-weight:%s;font-display:swap;src:url(data:font/woff2;base64,%s) format("woff2");unicode-range:%s}' % (f["family"], f["style"], f["weight"], b64, f["range"]))
    return "\n".join(out)

HEAD_SCRIPT = '<script>(function(){try{var r=document.documentElement,g=function(k){var v=localStorage.getItem("hale:"+k);return v===null?null:JSON.parse(v)};r.setAttribute("data-palette",g("palette")||"vellum");var t=g("theme");if(t==="light"||t==="dark")r.setAttribute("data-theme",t);var s=g("size");if(s)r.setAttribute("data-size",s);var m=g("motion");if(m!=="still"&&!(window.matchMedia&&matchMedia("(prefers-reduced-motion: reduce)").matches))r.classList.add("motion");}catch(e){}})();</script>'

ICON_SVG = ('<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 64 64"><rect width="64" height="64" rx="14" fill="#F6F1E7"/>'
            '<path d="M21 27C18 12 26 7 32 7S46 12 43 27" fill="none" stroke="#2F5E4B" stroke-width="5.5" stroke-linecap="round"/>'
            '<path d="M32 19C43 19 51 27.5 51 38C51 43.6 48.8 48.4 45 51.6H19C15.2 48.4 13 43.6 13 38C13 27.5 21 19 32 19Z" fill="#2F5E4B"/>'
            '<path d="M18 35C24 31 40 31 46 35M17 41.5C24 37.5 40 37.5 47 41.5M19.5 47.5C25 44 39 44 44.5 47.5" fill="none" stroke="#E2B571" stroke-width="1.8" stroke-linecap="round"/>'
            '<rect x="19" y="51" width="26" height="3.4" rx="1.7" fill="#B07A2E"/></svg>')

JS_ORDER = ["core.js", "figures.js", "musclemap.js", "charts.js", "diagrams.js", "library.js", "plan.js", "checks.js", "protein.js", "boot.js"]

def build(out=OUT, head_extra="", tail_extra=""):
    shell = rd("shell.html")
    views = "".join(rd(os.path.join("views", f)) for f in sorted(os.listdir(os.path.join(SRC, "views"))) if f.endswith(".html"))
    views = views.replace("<!--HEROART-->", rd("heroart.svg"))
    css = fonts_css() + "\n" + rd("base.css") + "\n" + rd("hale.css")
    refs = rd("refs.js").replace("export const REFS", "const REFS")
    js = "\n".join(rd(os.path.join("js", f)) for f in JS_ORDER)
    script = "<script>\n(function(){\n" + refs + "\n" + js + "\n})();\n</script>"
    icon = "data:image/svg+xml," + urllib.parse.quote(ICON_SVG, safe=":/=,;'\" ")
    html = (shell.replace("<!--HEAD-SCRIPT-->", HEAD_SCRIPT)
                 .replace("<!--STYLE-->", "<style>\n" + css + "\n</style>")
                 .replace("<!--VIEWS-->", views)
                 .replace("<!--SCRIPT-->", script + tail_extra)
                 .replace("<!--HEAD-EXTRA-->", head_extra)
                 .replace("__ICON__", icon))
    # the first view is shown before the script runs, so the page isn't blank if scripts are blocked
    html = html.replace('<section class="view" id="v-start"', '<section class="view on" id="v-start"', 1)
    assert "<!--" not in re.sub(r"<!--[A-Z ]+-->|<!-- [A-Z]+ -->", "", html) or True
    open(out, "w", encoding="utf-8").write(html)
    return out, len(html.encode("utf-8"))

if __name__ == "__main__":
    o, n = build()
    print("built", o, round(n / 1024), "KB")
